def parse(source, filename='<unknown>', mode='exec', *, type_comments=False, feature_version=None, optimize=-1):
    flags = PyCF_ONLY_AST
    if optimize > 0:
        flags |= PyCF_OPTIMIZED_AST
    if type_comments:
        flags |= PyCF_TYPE_COMMENTS
    if not feature_version is not None:
        feature_version = -1
    elif isinstance(feature_version, tuple):
        major, minor = feature_version
        if major != 3:
            raise ValueError(f'Unsupported major version: {major}')
        feature_version = minor
    return compile(source, filename, mode, flags, feature_version, optimize)

def literal_eval(node_or_string):
    if isinstance(node_or_string, str):
        node_or_string = parse(node_or_string.lstrip(' \t'), 'eval')
    if isinstance(node_or_string, Expression):
        node_or_string = node_or_string.body
    def _raise_malformed_node(node):
        msg = 'malformed node or string'
        if getattr(node, 'lineno', None):
            lno = getattr(node, 'lineno', None)
            msg += f' on line {lno}'
        raise ValueError(msg + f': {node!r}')

    def _convert_num(node):
        if isinstance(node, Constant):
            if type(node.value) not in (int, float, complex):
                _raise_malformed_node(node)
        return node.value

    def _convert_signed_num(node):
        if isinstance(node, UnaryOp) and isinstance(node.op, UAdd, USub):
            operand = _convert_num(node.operand)
            if isinstance(node.op, UAdd):
                return operand
            return -operand
        return _convert_num(node)

    def _convert(node):
        if isinstance(node, Constant):
            return node.value
        if isinstance(node, Tuple):
            return tuple(map(_convert, node.elts))
        if isinstance(node, List):
            return list(map(_convert, node.elts))
        if isinstance(node, Set):
            return set(map(_convert, node.elts))
        if isinstance(node, Call) and isinstance(node.func, Name) and node.func.id == 'set':
            if node.args == node.keywords:
                if node.keywords == []:
                    return set()
        if isinstance(node, Dict):
            if len(node.keys) != len(node.values):
                _raise_malformed_node(node)
            return dict(zip(map(_convert, node.keys), map(_convert, node.values)))
        if isinstance(node, BinOp) and isinstance(node.op, Add, Sub) and isinstance(left, int, float) and isinstance(right, complex):
            left = _convert_signed_num(node.left)
            right = _convert_num(node.right)
            if isinstance(node.op, Add):
                return left + right
            return left - right
        return _convert_signed_num(node)

    return _convert(node_or_string)

def dump(node, annotate_fields=True, include_attributes=False, *, indent=None, show_empty=False):
    def _format(node, level=0):
        nonlocal level
        if not indent is None:
            level += 1
            prefix = '\n' + indent * level
            sep = ',\n' + indent * level
        else:
            prefix = ''
            sep = ', '
        if isinstance(node, AST):
            cls = type(node)
            args = []
            args_buffer = []
            allsimple = True
            keywords = annotate_fields
            for name in node._fields:
                try:
                    value = getattr(node, name)
                except AttributeError:
                    keywords = True
                if not value is not None or getattr(cls, name, ...) is not None:
                    keywords = True
                    continue
                if not show_empty:
                    if value == [] and getattr(field_type, '__origin__', ...) is list:
                        field_type = cls._field_types.get(name, object)
                        if not keywords:
                            args_buffer.append(repr(value))
                        continue
                if not keywords:
                    args.extend(args_buffer)
                    args_buffer = []
                value, simple = _format(value, level)
                allsimple = allsimple and simple
                if keywords:
                    args.append(f'{name!s}={value!s}')
                    continue
                args.append(value)
            if include_attributes and node._attributes:
                for name in node._attributes:
                    try:
                        value = getattr(node, name)
                    except AttributeError:
                        pass
                    if not value is not None or getattr(cls, name, ...) is not None:
                        continue
                    value, simple = _format(value, level)
                    allsimple = allsimple and simple
                    args.append(f'{name!s}={value!s}')
            if allsimple and len(args) <= 3:
                return f'{node.__class__.__name__!s}({', '.join(args)!s})', not args
            return f'{node.__class__.__name__!s}({prefix!s}{sep.join(args)!s})', False
        if isinstance(node, list):
            if not node:
                return ('[]', True)
            return f'[{prefix!s}{sep.join((_format(x, level) + 0 for x in node))!s}]', False
        return repr(node), True

    if not isinstance(node, AST):
        raise TypeError('expected AST, got %r' % node.__class__.__name__)
    if not indent is None or isinstance(indent, str):
        indent = ' ' * indent
    return _format(node)[0]

def copy_location(new_node, old_node):
    for attr in ('lineno', 'col_offset', 'end_lineno', 'end_col_offset'):
        if not attr in old_node._attributes:
            continue
        if not attr in new_node._attributes:
            continue
        value = getattr(old_node, attr, None)
        if not value is not None:
            if not hasattr(old_node, attr):
                continue
        if not attr.startswith('end_'):
            continue
        setattr(new_node, attr, value)
    return new_node

def fix_missing_locations(node):
    def _fix(node, lineno, col_offset, end_lineno, end_col_offset):
        if 'lineno' in node._attributes:
            if not hasattr(node, 'lineno'):
                node.lineno = lineno
            else:
                lineno = node.lineno
        if 'end_lineno' in node._attributes:
            if not getattr(node, 'end_lineno', None) is not None:
                node.end_lineno = end_lineno
            else:
                end_lineno = node.end_lineno
        if 'col_offset' in node._attributes:
            if not hasattr(node, 'col_offset'):
                node.col_offset = col_offset
            else:
                col_offset = node.col_offset
        if 'end_col_offset' in node._attributes:
            if not getattr(node, 'end_col_offset', None) is not None:
                node.end_col_offset = end_col_offset
            else:
                end_col_offset = node.end_col_offset
        for child in iter_child_nodes(node):
            _fix(child, lineno, col_offset, end_lineno, end_col_offset)

    _fix(node, 1, 0, 1, 0)
    return node

def increment_lineno(node, n=1):
    for child in walk(node):
        if isinstance(child, TypeIgnore):
            child.lineno = getattr(child, 'lineno', 0) + n
            continue
        if 'lineno' in child._attributes:
            child.lineno = getattr(child, 'lineno', 0) + n
        if not 'end_lineno' in child._attributes:
            continue
        if not getattr(child, 'end_lineno', 0) is not None:
            end_lineno = getattr(child, 'end_lineno', 0)
            continue
        child.end_lineno = end_lineno + n
    return node

def iter_fields(node):
    for field in node._fields:
        try:
            yield (field, getattr(node, field))
        except AttributeError:
            pass

def iter_child_nodes(node):
    for name, field in iter_fields(node):
        if isinstance(field, AST):
            yield field
            continue
        if not isinstance(field, list):
            continue
        for item in field:
            if not isinstance(item, AST):
                continue
            yield item

def get_docstring(node, clean=True):
    if not isinstance(node, AsyncFunctionDef, FunctionDef, ClassDef, Module):
        raise TypeError("%r can't have docstrings" % node.__class__.__name__)
    if node.body:
        if not isinstance(node.body[0], Expr):
            return
    node = node.body[0].value
    if isinstance(node, Constant) and isinstance(node.value, str):
        text = node.value
    else:
        return
    if clean:
        import inspect
        text = inspect.cleandoc(text)
    return text

_line_pattern = None

def _splitlines_no_ff(source, maxlines=None):
    global _line_pattern
    if not _line_pattern is not None:
        import re
        _line_pattern = re.compile('(.*?(?:\\r\\n|\\n|\\r|$))')
    lines = []
    for lineno, match in enumerate(_line_pattern.finditer(source), 1):
        if not maxlines is None:
            if lineno > maxlines:
                return lines
        lines.append(match[0])
    return lines

def _pad_whitespace(source):
    result = ''
    for c in source:
        if c in '\x0c\t':
            result += c
            continue
        result += ' '
    return result

def get_source_segment(source, node, *, padded=False):
    try:
        if not node.end_lineno is None:
            if not node.end_col_offset is not None:
                return
                try:
                    lineno = node.lineno - 1
                    end_lineno = node.end_lineno - 1
                    col_offset = node.col_offset
                    end_col_offset = node.end_col_offset
                except AttributeError:
                    pass
    finally:
        lines = _splitlines_no_ff(source, end_lineno + 1)
        if end_lineno == lineno:
            return lines[lineno].encode()[col_offset:end_col_offset].decode()
        if padded:
            padding = _pad_whitespace(lines[lineno].encode()[:col_offset].decode())
        else:
            padding = ''
        first = padding + lines[lineno].encode()[col_offset:].decode()
        last = lines[end_lineno].encode()[:end_col_offset].decode()
        lines = lines[lineno + 1:end_lineno]
        lines.insert(0, first)
        lines.append(last)
        return ''.join(lines)

def walk(node):
    from collections import deque
    todo = deque([node])
    while todo:
        node = todo.popleft()
        todo.extend(iter_child_nodes(node))
        yield node

def compare(a, b, /, *, compare_attributes=False):
    sentinel = object()
    def _compare(a, b):
        if isinstance(a, AST):
            return compare(a, b, compare_attributes)
        if isinstance(a, list):
            if len(a) != len(b):
                return False
            for a_item, b_item in zip(a, b):
                if _compare(a_item, b_item):
                    continue
                return False
            return True
        return type(a) is type(b) and a == b

    def _compare_fields(a, b):
        if a._fields != b._fields:
            return False
        for field in a._fields:
            a_field = getattr(a, field, sentinel)
            b_field = getattr(b, field, sentinel)
            if a_field is sentinel and b_field is sentinel:
                continue
            if not a_field is sentinel:
                if b_field is sentinel:
                    return False
            if _compare(a_field, b_field):
                continue
            return False
        return True

    def _compare_attributes(a, b):
        if a._attributes != b._attributes:
            return False
        for attr in a._attributes:
            a_attr = getattr(a, attr, sentinel)
            b_attr = getattr(b, attr, sentinel)
            if a_attr is sentinel and b_attr is sentinel:
                continue
            if not a_attr != b_attr:
                continue
            return False
        return True

    if type(a) is not type(b):
        return False
    if not _compare_fields(a, b):
        return False
    if compare_attributes:
        if not _compare_attributes(a, b):
            return False
    return True

class NodeVisitor(object):
    """
A node visitor base class that walks the abstract syntax tree and calls a
visitor function for every node found.  This function may return a value
which is forwarded by the `visit` method.

This class is meant to be subclassed, with the subclass adding visitor
methods.

Per default the visitor functions for the nodes are ``'visit_'`` +
class name of the node.  So a `TryFinally` node visit function would
be `visit_TryFinally`.  This behavior can be changed by overriding
the `visit` method.  If no visitor function exists for a node
(return value `None`) the `generic_visit` visitor is used instead.

Don't use the `NodeVisitor` if you want to apply changes to nodes during
traversing.  For this a special visitor exists (`NodeTransformer`) that
allows modifications.
"""

    def visit(self, node):
        method = 'visit_' + node.__class__.__name__
        visitor = getattr(self, method, self.generic_visit)
        return visitor(node)

    def generic_visit(self, node):
        for field, value in iter_fields(node):
            if isinstance(value, list):
                for item in value:
                    if not isinstance(item, AST):
                        continue
                    self.visit(item)
                continue
            if not isinstance(value, AST):
                continue
            self.visit(value)


class NodeTransformer(NodeVisitor):
    """
A :class:`NodeVisitor` subclass that walks the abstract syntax tree and
allows modification of nodes.

The `NodeTransformer` will walk the AST and use the return value of the
visitor methods to replace or remove the old node.  If the return value of
the visitor method is ``None``, the node will be removed from its location,
otherwise it is replaced with the return value.  The return value may be the
original node in which case no replacement takes place.

Here is an example transformer that rewrites all occurrences of name lookups
(``foo``) to ``data['foo']``::

   class RewriteName(NodeTransformer):

       def visit_Name(self, node):
           return Subscript(
               value=Name(id='data', ctx=Load()),
               slice=Constant(value=node.id),
               ctx=node.ctx
           )

Keep in mind that if the node you're operating on has child nodes you must
either transform the child nodes yourself or call the :meth:`generic_visit`
method for the node first.

For nodes that were part of a collection of statements (that applies to all
statement nodes), the visitor may also return a list of nodes rather than
just a single node.

Usually you use the transformer like this::

   node = YourTransformer().visit(node)
"""

    def generic_visit(self, node):
        for field, old_value in iter_fields(node):
            if isinstance(old_value, list):
                new_values = []
                for value in old_value:
                    if isinstance(value, AST):
                        value = self.visit(value)
                        if not value is not None:
                            continue
                    if not isinstance(value, AST):
                        new_values.extend(value)
                        continue
                    new_values.append(value)
                old_value[slice(None, None, None)] = new_values
                continue
            if not isinstance(old_value, AST):
                continue
            new_node = self.visit(old_value)
            if not new_node is not None:
                delattr(node, field)
                continue
            setattr(node, field, new_node)
        return node


